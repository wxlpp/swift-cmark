#!/usr/bin/env python3
"""Generate frozen Unicode 18 tables; no host Unicode database or network."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
DATA = ROOT / 'tools/cjk-data/18.0.0'


def properties(name):
    for line in (DATA / name).read_text().splitlines():
        line = line.split('#', 1)[0].strip()
        if not line:
            continue
        key, value, *_ = [part.strip() for part in line.split(';')]
        yield key, value


def points(key):
    ends = [int(n, 16) for n in key.split('..')]
    return range(ends[0], ends[-1] + 1)


def ranges(values):
    result = []
    for value in sorted(values):
        if result and value == result[-1][1] + 1:
            result[-1][1] = value
        else:
            result.append([value, value])
    return result


def generate():
    manifest = json.loads((ROOT / 'tools/cjk-data/manifest.json').read_text())
    assert manifest['unicodeVersion'] == '18.0.0'
    for entry in manifest['inputs']:
        assert hashlib.sha256((ROOT / entry['path']).read_bytes()).hexdigest() == entry['sha256'], entry['path']
    wide, ambiguous, hangul, emoji = set(), set(), set(), set()
    for key, prop in properties('EastAsianWidth.txt'):
        if prop in ('W', 'F', 'H'):
            wide.update(points(key))
        elif prop == 'A':
            ambiguous.update(points(key))
    # UAX #11 defaults for reserved ideographic code points.
    for lo, hi in ((0x3400, 0x4DBF), (0x4E00, 0x9FFF), (0xF900, 0xFAFF), (0x20000, 0x2FFFD), (0x30000, 0x3FFFD)):
        wide.update(range(lo, hi + 1))
    for key, prop in properties('Scripts.txt'):
        if prop == 'Hangul':
            hangul.update(points(key))
    for key, prop in properties('emoji/emoji-data.txt'):
        if prop == 'Emoji_Presentation':
            emoji.update(points(key))
    punctuation, space = set(), {9, 10, 12, 13}
    first = None
    for line in (DATA / 'UnicodeData.txt').read_text().splitlines():
        fields = line.split(';')
        cp, name, category = int(fields[0], 16), fields[1], fields[2]
        if name.endswith(', First>'):
            first = cp
            continue
        values = range(first, cp + 1) if name.endswith(', Last>') else [cp]
        if name.endswith(', Last>'):
            first = None
        if category[0] in ('P', 'S'):
            punctuation.update(values)
        if category == 'Zs':
            space.update(values)
    cjk = (wide - emoji) | hangul
    pairs = []
    for key, description in properties('StandardizedVariants.txt'):
        base, selector = [int(n, 16) for n in key.split()]
        if 'fullwidth form' in description and base in ambiguous and base in punctuation:
            pairs.append([base, selector])
    # Explicit non-examples prevent confusing Unicode White_Space with CommonMark.
    assert not ({0xB, 0x85, 0x2028, 0x2029} & space)
    assert {0x3030, 0x303D, 0x3297, 0x3299, 0x1F202, 0x1F237, 0x1160} <= cjk
    assert 0x1F600 not in cjk and 0x4E00 in cjk and 0x20000 in cjk
    text = ['/* Generated by tools/generate-cjk-tables.py; Unicode 18.0.0.',
            ' * See tools/cjk-data/manifest.json and 18.0.0/LICENSE.txt. */',
            '#ifndef CMARK_CJK_TABLES_H', '#define CMARK_CJK_TABLES_H',
            '#include <stdint.h>', '#include <stddef.h>',
            'typedef struct { int32_t first, last; } cmark_cjk_range;']
    for name, values in [('cjk', cjk), ('punctuation', punctuation), ('space', space)]:
        text += [f'static const cmark_cjk_range cmark_cjk_{name}_ranges[] = {{']
        text += [f'  {{0x{lo:X}, 0x{hi:X}}},' for lo, hi in ranges(values)]
        text += ['};']
    text += ['static const cmark_cjk_range cmark_cjk_fullwidth_pairs[] = {']
    text += [f'  {{0x{base:X}, 0x{selector:X}}},' for base, selector in sorted(pairs)]
    text += ['};', '#endif', '']
    return '\n'.join(text)


if __name__ == '__main__':
    import sys
    output = ROOT / 'src/cjk_tables.h'
    content = generate()
    if '--check' in sys.argv:
        assert output.read_text() == content, 'CJK tables are stale'
        print('Frozen inputs and generated CJK tables verified')
    else:
        output.write_text(content)
